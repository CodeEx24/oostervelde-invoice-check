import type { Finding, InvoiceReview } from "./types.js";

const V = { approve: "APPROVE", dispute: "DISPUTE", hold: "HOLD" } as const;

export const totalDisputeIncl = (r: InvoiceReview) => r.disputeExclCents + r.disputeVatCents + r.disputeOtherCents;
export const netPayableIncl = (r: InvoiceReview) =>
  r.billedInclCents - totalDisputeIncl(r) + (r.invoice.isCredit ? 0 : r.creditAppliedInclCents);

export interface Totals {
  invoices: number; approve: number; dispute: number; hold: number;
  excl: number; vat: number; other: number; incl: number; holdBilledIncl: number; needsSanne: number;
}
export function totals(rs: InvoiceReview[]): Totals {
  const t: Totals = { invoices: rs.length, approve: 0, dispute: 0, hold: 0, excl: 0, vat: 0, other: 0, incl: 0, holdBilledIncl: 0, needsSanne: 0 };
  for (const r of rs) {
    t[r.verdict]++;
    t.excl += r.disputeExclCents; t.vat += r.disputeVatCents; t.other += r.disputeOtherCents;
    if (r.verdict === "hold") t.holdBilledIncl += r.billedInclCents;
    if (r.needsSanne) t.needsSanne++;
  }
  t.incl = t.excl + t.vat + t.other;
  return t;
}

/** Plain JSON for tools / files: cents plus Dutch-formatted strings. */
export function findingView(f: Finding) {
  return {
    id: f.id, article: f.article, kind: f.kind, severity: f.severity, confidence: f.confidence, lines: f.lineNos,
    disputeExclCents: f.disputeExclCents, disputeVatCents: f.disputeVatCents, disputeOtherCents: f.disputeOtherCents,
    disputeExcl: eur(f.disputeExclCents), disputeVat: eur(f.disputeVatCents), disputeOther: eur(f.disputeOtherCents),
    title: f.titleEn, reasonEn: f.reasonEn, reasonNl: f.reasonNl, evidence: f.evidence, contractQuoteNl: f.contractQuoteNl,
  };
}

export function reviewView(r: InvoiceReview) {
  return {
    file: r.invoice.file, supplier: r.invoice.supplier, invoiceNo: r.invoice.invoiceNo, invoiceDate: r.invoice.invoiceDate,
    executionDate: r.invoice.executionDate, workOrder: r.invoice.workOrder, isCredit: r.invoice.isCredit,
    verdict: r.verdict, verdictReason: r.verdictReasonEn, needsSanne: r.needsSanne,
    billedExcl: eur(r.billedExclCents), billedIncl: eur(r.billedInclCents),
    disputeExclCents: r.disputeExclCents, disputeVatCents: r.disputeVatCents, disputeOtherCents: r.disputeOtherCents,
    disputeExcl: eur(r.disputeExclCents), disputeVat: eur(r.disputeVatCents), disputeOther: eur(r.disputeOtherCents),
    disputeTotalIncl: eur(totalDisputeIncl(r)),
    netPayableIncl: r.verdict === "hold" ? "on hold" : eur(netPayableIncl(r)),
    respondByDate: r.verdict === "approve" ? null : addWorkdays(r.invoice.invoiceDate, 10),
    findings: r.findings.map(findingView),
  };
}

const flag = (r: InvoiceReview) => (r.needsSanne ? " ⚠" : "");

export function renderReviewList(rs: InvoiceReview[], ctx: Context): string {
  const t = totals(rs);
  const L: string[] = [];
  L.push("# Review list: January 2026 invoices, Woonkring Oostervelde");
  L.push("");
  L.push("_Generated by the Oostervelde invoice-check engine. Proposed verdicts only: **Sanne decides every invoice**; nothing is sent to a contractor without her approval._");
  L.push("");
  L.push("## Totals");
  L.push("");
  L.push(`| | |`);
  L.push(`|---|---:|`);
  L.push(`| Invoices reviewed | ${t.invoices} |`);
  L.push(`| Proposed APPROVE | ${t.approve} |`);
  L.push(`| Proposed DISPUTE | ${t.dispute} |`);
  L.push(`| Proposed HOLD | ${t.hold} |`);
  L.push(`| **To dispute, excl. VAT** | **${eur(t.excl)}** |`);
  L.push(`| VAT on the disputed amounts / wrong-rate VAT | ${eur(t.vat)} |`);
  L.push(`| Arithmetic errors in invoice totals (no VAT component) | ${eur(t.other)} |`);
  L.push(`| **Total to dispute, incl. VAT** | **${eur(t.incl)}** |`);
  L.push(`| Billed on invoices on HOLD (not payable yet) | ${eur(t.holdBilledIncl)} |`);
  L.push(`| Invoices that need Sanne's judgment (⚠) | ${t.needsSanne} |`);
  L.push("");
  L.push("Amounts are in euro, Dutch notation (1.234,56). Dispute amounts are what the contract does NOT allow; the undisputed part is paid within 30 days (Art. 4.10). The 10-working-day deadline to notify the contractor (Art. 4.10) is counted here from the invoice date because the received-date is not in the data.");
  L.push("");
  L.push("## All invoices");
  L.push("");
  L.push("| # | File | Supplier | Invoice | Work order | Verdict | Disputed excl. VAT | VAT | Other | Total disputed | Net payable (incl.) |");
  L.push("|---:|---|---|---|---|---|---:|---:|---:|---:|---:|");
  rs.forEach((r, i) => {
    L.push(`| ${i + 1} | ${r.invoice.file} | ${r.invoice.supplier} | ${r.invoice.invoiceNo}${r.invoice.isCredit ? " (credit)" : ""} | ${r.invoice.workOrder ?? "-"} | **${V[r.verdict]}**${flag(r)} | ${fmt(r.disputeExclCents)} | ${fmt(r.disputeVatCents)} | ${fmt(r.disputeOtherCents)} | ${fmt(totalDisputeIncl(r))} | ${r.verdict === "hold" ? "on hold" : fmt(netPayableIncl(r))} |`);
  });
  L.push("");
  L.push("## Invoices that are not a plain approve");
  for (const r of rs.filter((x) => x.verdict !== "approve" || x.findings.some((f) => f.severity !== "info" || f.kind === "credit-note"))) {
    L.push("");
    L.push(`### ${r.invoice.supplier} ${r.invoice.invoiceNo} — ${V[r.verdict]}${flag(r)}`);
    L.push("");
    L.push(`File \`${r.invoice.file}\` · work order ${r.invoice.workOrder ?? "-"} · invoice date ${r.invoice.invoiceDate} · executed ${r.invoice.executionDate ?? "?"} · billed ${eur(r.billedInclCents)} incl. VAT.`);
    L.push("");
    L.push(`**Why:** ${r.verdictReasonEn}`);
    if (r.verdict === "dispute") L.push(`**Dispute:** ${eur(r.disputeExclCents)} excl. VAT + ${eur(r.disputeVatCents)} VAT${r.disputeOtherCents ? ` + ${eur(r.disputeOtherCents)} total error` : ""} = **${eur(totalDisputeIncl(r))}**. Net payable (undisputed part): ${eur(netPayableIncl(r))} incl. VAT. Notify contractor by ${addWorkdays(r.invoice.invoiceDate, 10)}.`);
    if (r.creditAppliedInclCents) L.push(`**Credit notes netted:** ${eur(r.creditAppliedInclCents)} incl. VAT.`);
    for (const f of r.findings) {
      L.push("");
      const tag = f.severity === "info" ? "info" : f.severity;
      L.push(`- **[Art. ${f.article} · ${tag}${f.confidence === "judgment" ? " · ⚠ judgment" : ""}] ${f.titleEn}**`);
      if (f.disputeExclCents || f.disputeVatCents || f.disputeOtherCents) L.push(`  - Amount: ${eur(f.disputeExclCents)} excl. VAT${f.disputeVatCents ? ` + ${eur(f.disputeVatCents)} VAT` : ""}${f.disputeOtherCents ? ` + ${eur(f.disputeOtherCents)} total error` : ""}${f.lineNos.length ? ` (line ${f.lineNos.join(", ")})` : ""}`);
      L.push(`  - Reason: ${f.reasonEn}`);
      for (const e of f.evidence) L.push(`  - Evidence: \`${e}\``);
      L.push(`  - Contract: ${f.contractQuoteNl}`);
      L.push(`  - Voor de aannemer: ${f.reasonNl}`);
    }
  }
  L.push("");
  L.push("## Approved invoices (no findings)");
  L.push("");
  L.push(rs.filter((r) => r.verdict === "approve" && !r.findings.some((f) => f.severity !== "info" || f.kind === "credit-note")).map((r) => `${r.invoice.invoiceNo} (${r.invoice.supplier}, ${r.invoice.workOrder})`).join(" · "));
  L.push("");
  return L.join("\n");
}

export function renderCsv(rs: InvoiceReview[]): string {
  const rows: (string | number)[][] = [["file", "supplier", "invoice_no", "work_order", "execution_date", "verdict", "needs_sanne", "billed_incl", "disputed_excl", "disputed_vat", "disputed_other", "disputed_total_incl", "findings"]];
  const c = (n: number) => (n / 100).toFixed(2);
  for (const r of rs) {
    rows.push([r.invoice.file, r.invoice.supplier, r.invoice.invoiceNo, r.invoice.workOrder ?? "", r.invoice.executionDate ?? "", r.verdict, r.needsSanne ? "yes" : "no",
      c(r.billedInclCents), c(r.disputeExclCents), c(r.disputeVatCents), c(r.disputeOtherCents), c(totalDisputeIncl(r)),
      r.findings.filter((f) => f.severity !== "info").map((f) => `${f.article} ${f.kind}`).join("; ")]);
  }
  return toCsv(rows);
}

/** Dutch dispute / correction e-mail DRAFT for Sanne. Never sent by the tool. */
export function renderDraftEmail(r: InvoiceReview): string | null {
  if (r.verdict === "approve") return null;
  const inv = r.invoice;
  const open = r.findings.filter((f) => f.severity !== "info");
  const L: string[] = [];
  L.push("CONCEPT — nog niet verzonden. Sanne beslist of en wanneer dit wordt verstuurd.");
  L.push("");
  L.push(`Aan: ${inv.supplier} (crediteurenadministratie)`);
  L.push(`Onderwerp: ${r.verdict === "hold" ? "Factuur" : "Betwisting factuur"} ${inv.invoiceNo}${inv.workOrder ? ` — werkorder ${inv.workOrder}` : ""}`);
  L.push("");
  L.push("Geachte heer/mevrouw,");
  L.push("");
  if (r.verdict === "dispute") {
    L.push(`Wij hebben uw factuur ${inv.invoiceNo} van ${dutchDate(inv.invoiceDate)}${inv.workOrder ? ` (werkorder ${inv.workOrder})` : ""} gecontroleerd aan de hand van de raamovereenkomst planmatig en dagelijks onderhoud 2025-2027. Op grond van artikel 4.10 melden wij u hierbij schriftelijk en met reden dat wij de volgende onderdelen betwisten:`);
  } else {
    L.push(`Wij hebben uw factuur ${inv.invoiceNo} van ${dutchDate(inv.invoiceDate)} gecontroleerd aan de hand van de raamovereenkomst planmatig en dagelijks onderhoud 2025-2027. Wij kunnen de factuur nog niet betalen om de volgende reden(en):`);
  }
  L.push("");
  open.forEach((f, i) => {
    L.push(`${i + 1}. ${f.reasonNl}`);
    L.push(`   Contract: ${f.contractQuoteNl}`);
    if (f.disputeExclCents || f.disputeVatCents || f.disputeOtherCents) {
      L.push(`   Betwist bedrag: ${eur(f.disputeExclCents)} excl. btw${f.disputeVatCents ? ` (btw daarover: ${eur(f.disputeVatCents)})` : ""}${f.disputeOtherCents ? ` (rekenfout in het totaal: ${eur(f.disputeOtherCents)})` : ""}.`);
    }
    L.push("");
  });
  if (r.verdict === "dispute") {
    L.push(`In totaal betwisten wij ${eur(r.disputeExclCents)} excl. btw en ${eur(r.disputeVatCents)} btw${r.disputeOtherCents ? ` en ${eur(r.disputeOtherCents)} rekenfout` : ""}, samen ${eur(totalDisputeIncl(r))} incl. btw. Het onbetwiste deel (${eur(netPayableIncl(r))} incl. btw) betalen wij binnen 30 dagen na ontvangst van de factuur (art. 4.10).`);
    L.push("");
    L.push(`Wilt u een creditfactuur sturen die verwijst naar factuur ${inv.invoiceNo} (art. 4.8), of uw standpunt onderbouwen?`);
  } else {
    L.push("Zodra dit is opgelost, nemen wij de factuur in behandeling.");
  }
  L.push("");
  L.push("Met vriendelijke groet,");
  L.push("");
  L.push("Sanne Verbeek");
  L.push("Crediteurenadministratie, Woonkring Oostervelde");
  return L.join("\n");
}
